import numpy as np

def jacobi(A,B,N=25,x=None):
    """Solves the equation Ax=b via the Jacobi iterative method."""
                         
    if x is None:
        x = np.zeros(len(A[0]))
                   
    D = np.diag(A)
                                     
    for n in range(N):

        x_old = x.copy()

        for i in range(np.size(A, 0)):

            sum = 0
            for j in range(np.size(A, 1)):
                if(i == j):
                    continue
                sum += A[i, j] * x_old[j]

            x[i] = (B[i] - sum) / D[i]

    x = np.transpose(x)
    return x

